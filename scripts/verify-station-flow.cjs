const { chromium, expect } = require('@playwright/test')
const { spawn, spawnSync } = require('node:child_process')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
;(async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'tunaeye-station-')), database = path.join(directory, 'station.sqlite3')
  const server = spawn('python', ['server/station.py', '--port', '4198', '--database', database], { windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] })
  await new Promise((resolve, reject) => { server.stdout.once('data', resolve); server.once('error', reject); server.once('exit', code => reject(Error(`Station exited ${code}`))) })
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1024, height: 600 }, hasTouch: true }), page = await context.newPage(), errors = []
    page.on('pageerror', error => errors.push(error.message))
    const image = fs.readFileSync('public/assets/sashiboCoreFull.png')
    let piRequests = 0
    await page.route('**/status', route => { piRequests++; return route.fulfill({ contentType: 'application/json', body: JSON.stringify({ service: 'Fixture Pi Flask', models: { sashibocore: true, tailcut: true } }) }) })
    for (const endpoint of ['snapshot', 'stream']) await page.route(`**/${endpoint}`, route => { piRequests++; return route.fulfill({ contentType: 'image/png', body: image }) })
    await page.route('**/grade', route => { piRequests++; return route.fulfill({ contentType: 'application/json', body: JSON.stringify({ id: 'fixture-real-contract', capture_id: 'fixture-capture', image_type: 'sashibocore', grade: 'GRADE_C', confidence: .91, scores: { GRADE_A: .03, GRADE_B: .04, GRADE_C: .91, INVALID: .02 } }) }) })
    async function open() {
      await page.goto('http://127.0.0.1:4198/')
      await page.locator('iframe[title=TunaEye]').waitFor()
      const landing = page.frames().find(frame => frame.parentFrame()); await landing.locator('.hero').waitFor()
      await landing.evaluate(() => window.openKiosk()); await landing.locator('#kiosk-wrap iframe').waitFor()
      const kiosk = page.frames().find(frame => frame.parentFrame() === landing)
      await expect.poll(() => kiosk.evaluate(() => Boolean(window.__tunaeyeAttached))).toBe(true)
      return kiosk
    }
    let kiosk = await open()
    await kiosk.locator('#gs').click(); await kiosk.locator('#in').fill('Station persistence QA'); await kiosk.locator('#go').click()
    const ready = kiosk.getByRole('dialog', { name: 'Ready for live grading?' })
    await expect(ready.getByRole('button', { name: 'Start live grading' })).toBeEnabled({ timeout: 15000 })
    await ready.getByRole('button', { name: 'Start live grading' }).click()
    await kiosk.locator('[data-k="8"]').click(); await kiosk.locator('[data-k="5"]').click(); await kiosk.locator('#go').click()
    if (await kiosk.locator('#tps').isVisible()) await kiosk.locator('#tps').click()
    await kiosk.locator('#sh').click(); await expect(kiosk.locator('.med5-l')).toHaveText('C', { timeout: 20000 })
    await expect(kiosk.getByRole('status')).toContainText('Saved to SQLite')
    const stored = spawnSync('python', ['server/station.py', '--database', database, '--request'], { input: JSON.stringify({ method: 'GET', path: '/local-api/records' }), encoding: 'utf8' })
    expect(stored.status).toBe(0)
    const rows = JSON.parse(stored.stdout).records; expect(rows).toHaveLength(1); expect(rows[0].grade).toBe('C'); expect(rows[0].result.originalConfidence).toBe(91)
    const evidenceId = rows[0].capturedImageId
    const evidence = await (await page.request.get(`http://127.0.0.1:4198/local-api/evidence/${encodeURIComponent(evidenceId)}`)).json()
    expect(Buffer.from(evidence.evidence.image, 'base64').equals(image)).toBe(true)
    await page.evaluate(async () => { localStorage.clear(); await new Promise((resolve, reject) => { const r = indexedDB.deleteDatabase('tunaeye-offline'); r.onsuccess = resolve; r.onerror = reject }) })
    kiosk = await open()
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem('tunaeye-records')).length)).toBe(1)
    await kiosk.evaluate(() => { S.tab = 'records'; go('admin') })
    await kiosk.getByRole('button', { name: `Review ${rows[0].id}` }).click()
    await expect(kiosk.getByAltText('Captured Sashibo core')).toBeVisible()
    await expect.poll(() => kiosk.getByAltText('Captured Sashibo core').evaluate(img => img.naturalWidth)).toBeGreaterThan(0)
    await page.evaluate(() => navigator.serviceWorker.ready)
    await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller))
    await context.setOffline(true)
    kiosk = await open()
    await kiosk.locator('#gs').click(); await kiosk.locator('#dmsw').click(); await kiosk.locator('#in').fill('Offline demo QA')
    await kiosk.getByRole('combobox', { name: 'Demo scenario' }).selectOption('needs-tail')
    const requestsBeforeDemo = piRequests
    await kiosk.locator('#go').click(); await kiosk.locator('[data-k="8"]').click(); await kiosk.locator('[data-k="5"]').click(); await kiosk.locator('#go').click()
    if (await kiosk.locator('#tps').isVisible()) await kiosk.locator('#tps').click()
    await kiosk.locator('#sh').click(); await expect(kiosk.locator('#go')).toContainText(/tail/i, { timeout: 15000 }); await kiosk.locator('#go').click()
    await kiosk.locator('#sh').click(); await expect(kiosk.locator('.med5-l')).toHaveText('B', { timeout: 15000 })
    await expect(kiosk.locator('.lg5')).toContainText('Simulated prediction')
    await kiosk.evaluate(() => { window.printCalls = 0; document.addEventListener('load', event => { if (event.target.matches?.('iframe[data-thermal-receipt]')) event.target.contentWindow.print = () => { window.printCalls++ } }, true) })
    await kiosk.locator('#go').click(); await expect(kiosk.locator('.rh1')).toBeVisible(); await expect.poll(() => kiosk.evaluate(() => window.printCalls)).toBe(1)
    expect(piRequests).toBe(requestsBeforeDemo)
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem('tunaeye-records')).length)).toBe(1)
    await context.setOffline(false)
    expect((await (await page.request.get('http://127.0.0.1:4198/local-api/health')).json()).writable).toBe(true)
    fs.mkdirSync('test-results/station-flow', { recursive: true }); await page.screenshot({ path: 'test-results/station-flow/offline-receipt.png' })
    expect(errors).toEqual([])
    console.log('PASS real SQLite row/image transaction, browser-data-loss recovery, evidence restored, localhost production offline reload, complete offline core→tail→B→auto receipt, demo isolation and reconnect; Pi and print transport mocked')
    await context.close()
  } finally { await browser.close(); server.kill() }
})().catch(error => { console.error(error); process.exit(1) })
