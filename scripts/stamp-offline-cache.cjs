const fs = require('fs')
const path = require('path')
const { createHash } = require('crypto')
const dist = path.resolve('dist')
const worker = path.join(dist, 'sw.js')
// A changed entry or imported chunk must trigger a new worker install and a coherent shell cache.
const bundles = fs.readdirSync(path.join(dist, 'assets')).filter(file => /\.(js|css)$/.test(file)).sort()
const hash = createHash('sha256')
for (const file of bundles) hash.update(fs.readFileSync(path.join(dist, 'assets', file)))
const source = fs.readFileSync(worker, 'utf8')
const stamped = source.replace(/^const CACHE = '[^']+'/m, `const CACHE = 'tunaeye-build-${hash.digest('hex').slice(0, 16)}'`)
if (source === stamped) throw Error('Offline cache version was not stamped.')
fs.writeFileSync(worker, stamped)
console.log('Stamped deployment-specific TunaEye offline cache')
