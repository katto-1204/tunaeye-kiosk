const { chromium, expect, devices } = require('@playwright/test')
const fs = require('fs')
;(async () => {
  const b = await chromium.launch({ channel: 'chrome', headless: true, args: ['--disable-gpu', '--disable-software-rasterizer'] })
  try {
    const c = await b.newContext({ viewport: { width: 1280, height: 800 } }), p = await c.newPage()
    const errors = []; p.on('pageerror', e => errors.push(e.message))
    let modelsReady = false, sqliteWrites = 0, cloudWrites = 0
    p.on('request', request => { if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(request.method()) && request.url().includes('supabase')) cloudWrites++ })
    await p.route('https://fonts.googleapis.com/**', route => route.fulfill({ contentType: 'text/css', body: '' }))
    await p.route('**/status', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ service: 'Fixture Flask', models: { sashibocore: true, tailcut: modelsReady } }) }))
    await p.route('**/snapshot', route => route.fulfill({ contentType: 'image/png', body: fs.readFileSync('public/assets/sashiboCoreFull.png') }))
    await p.route('**/local-api/health', route => route.fulfill({ contentType: 'application/json', body: '{"sqlite":"ready","writable":true}' }))
    await p.route('**/local-api/records', route => { const post = route.request().method() === 'POST'; if (post) sqliteWrites++; return route.fulfill({ contentType: 'application/json', body: JSON.stringify(post ? { saved: route.request().postDataJSON().record.id } : { records: [] }) }) })
    await p.goto('http://127.0.0.1:4185/', { waitUntil: 'domcontentloaded' })
    await expect(p.getByRole('status', { name: 'Opening TunaEye' })).toBeVisible()
    await expect(p.getByRole('status')).toHaveCount(0)
    const l = p.frames().find(f => f.parentFrame()); await l.locator('.hero').waitFor()
    await l.locator('[data-act="start"]').first().click()
    await expect(p.getByRole('status', { name: 'Opening grading kiosk' })).toBeVisible()
    await expect(p.getByRole('status')).toHaveCount(0)
    await l.locator('#kiosk-wrap iframe').waitFor(); const k = p.frames().find(f => f.parentFrame() === l)
    await expect.poll(() => k.evaluate(() => Boolean(window.__tunaeyeAttached))).toBe(true)
    await expect(k.locator('#station-mode')).toHaveCount(0)
    await k.evaluate(() => go('name'))
    await k.locator('#dmsw').click({ force: true }); await expect(k.locator('#dmsw')).toHaveAttribute('aria-checked', 'true')
    let gradeCalls = 0; await p.route('**/grade', r => { gradeCalls++; return r.abort() })
    await k.evaluate(() => { S.w = '85'; S.name = 'Demo QA'; go('core') })
    await k.locator('#sh').click({ force: true }); await expect(k.locator('.med5-l')).toHaveText('A', { timeout: 20000 })
    if (gradeCalls !== 0) throw Error('Demo called live inference')
    if (await p.evaluate(() => JSON.parse(localStorage.getItem('tunaeye-records') || '[]').length)) throw Error('Demo polluted operational records')
    if (sqliteWrites) throw Error('Demo wrote operational SQLite records')
    await expect(k.locator('#station-mode')).toHaveCount(0)
    await k.evaluate(() => go('name')); await k.locator('#dmsw').click({ force: true })
    const readiness = k.getByRole('dialog', { name: 'Ready for live grading?' })
    await expect(readiness.locator('[data-live-check=tailcut]')).toContainText('not loaded')
    await expect(readiness.getByRole('button', { name: 'Start live grading', exact: true })).toBeDisabled()
    await expect(k.locator('#dmsw')).toHaveAttribute('aria-checked', 'true')
    modelsReady = true; await readiness.getByRole('button', { name: 'Retry checks', exact: true }).click({ force: true })
    await expect(readiness.getByRole('button', { name: 'Start live grading', exact: true })).toBeEnabled()
    await readiness.getByRole('button', { name: 'Start live grading', exact: true }).click({ force: true })
    await expect(k.locator('#dmsw')).toHaveAttribute('aria-checked', 'false')
    await k.evaluate(() => { S.pin = ''; go('pin') })
    await k.evaluate(() => { window.pinKeypad = document.querySelector('.kp') })
    for (const digit of [1, 2, 3]) {
      await k.locator(`[data-k="${digit}"]`).click({ force: true })
      expect(await k.evaluate(() => document.querySelector('.kp') === window.pinKeypad)).toBe(true)
    }
    await k.locator('[data-k="4"]').click({ force: true })
    await expect(k.locator('.ea')).toBeVisible()
    await k.locator('.an[data-t="graders"]').click({ force: true }); await k.locator('#ea-grader-name').fill('Admin transfer QA'); await k.locator('#ea-grader-add').click({ force: true })
    await expect(k.getByText('Admin transfer QA', { exact: true })).toBeVisible()
    await k.getByRole('button', { name: 'Remove Admin transfer QA', exact: true }).click({ force: true }); await k.locator('#mk').click({ force: true })
    await expect(k.getByText('Admin transfer QA', { exact: true })).toHaveCount(0)
    await k.locator('.an[data-t="settings"]').click({ force: true }); await k.locator('#ea-station').fill('Verified station'); await k.locator('#ea-settings-save').click({ force: true })
    if (await p.evaluate(() => localStorage.getItem('tunaeye-station')) !== 'Verified station') throw Error('Settings did not persist')
    const pinForm = k.locator('form').filter({ has: k.getByRole('heading', { name: 'Administrator PIN', exact: true }) })
    await pinForm.getByLabel('Current PIN', { exact: true }).fill('1234')
    await pinForm.getByLabel('New PIN', { exact: true }).fill('2468')
    await pinForm.getByRole('button', { name: 'Change PIN', exact: true }).click({ force: true })
    await expect(pinForm.getByRole('status')).toContainText('updated')
    await k.locator('.an[data-t="records"]').click({ force: true }); await expect(k.locator('#ea-search')).toBeVisible(); await expect(k.locator('#ea-prev')).toBeDisabled()
    require('fs').mkdirSync('test-results/exact-followup', { recursive: true })
    await p.waitForTimeout(1000) // Capture after the supplied screen entrance animation.
    await p.screenshot({ path: 'test-results/exact-followup/admin.png' })
    await k.locator('#lo').click({ force: true }); await k.locator('#mk').click({ force: true })
    await expect(k.locator('#gs')).toBeVisible()
    await k.evaluate(() => { S.pin = ''; go('pin') })
    for (const digit of [1, 2, 3, 4]) await k.locator(`[data-k="${digit}"]`).click({ force: true })
    await expect(k.getByRole('alert')).toContainText('Incorrect PIN')
    for (const digit of [2, 4, 6, 8]) await k.locator(`[data-k="${digit}"]`).click({ force: true })
    await expect(k.locator('.ea')).toBeVisible()
    if (cloudWrites) throw Error('Admin regression test unexpectedly wrote cloud data')
    if (errors.length) throw Error(errors.join('\n'))
    console.log('PASS dial startup/transition; live readiness blocks unloaded model/retries; demo isolation; PIN keypad without rerender; grader CRUD/settings/record pagination; PIN rotation/logout/relogin; zero cloud writes; no page errors')
    await c.close()
    const tablet = await b.newContext({ ...devices['iPad (gen 7)'], viewport: { width: 1024, height: 768 } }), tp = await tablet.newPage()
    await tp.route('**/local-api/records', route => route.fulfill({ contentType: 'application/json', body: '{"records":[]}' }))
    await tp.route('https://fonts.googleapis.com/**', route => route.fulfill({ contentType: 'text/css', body: '' }))
    await tp.goto('http://127.0.0.1:4185/')
    await expect.poll(() => tp.frames().length).toBe(3)
    const tk = tp.frames().find(f => f.parentFrame()?.parentFrame())
    await expect(tk.locator('#gs')).toBeVisible()
    console.log('PASS tablet automatically bypasses landing to kiosk')
    await tablet.close()
  } finally { await b.close() }
})().catch(e => { console.error(e); process.exit(1) })
