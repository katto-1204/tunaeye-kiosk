const { chromium, expect } = require('@playwright/test')
const fs = require('fs')
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 800 } })
    const page = await context.newPage(), errors = [], requests = []
    page.on('pageerror', e => errors.push(e.message))
    await page.route('**/status', route => route.fulfill({ contentType: 'application/json', body: '{"models":{"sashibocore":true,"tailcut":true}}' }))
    await page.route('**/local-api/**', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify(route.request().method() === 'POST' ? { saved: route.request().postDataJSON().record.id } : route.request().url().endsWith('/health') ? { sqlite: 'ready', writable: true } : { records: [] }) }))
    await page.route('https://fonts.googleapis.com/**', r => r.fulfill({ contentType: 'text/css', body: '' }))
    page.on('requestfailed', r => { if (r.failure()?.errorText !== 'net::ERR_ABORTED') errors.push(`${r.url()}: ${r.failure()?.errorText}`) })
    const image = fs.readFileSync('public/assets/sashiboCoreFull.png')
    await page.route('http://10.42.0.1:8080/**', route => route.fulfill({ contentType: 'image/png', body: image }))
    await page.route('**/snapshot', route => route.fulfill({ contentType: 'image/png', body: image }))
    await page.route('**/stream?**', route => route.fulfill({ contentType: 'image/png', body: image }))
    await page.route('**/stream', route => route.fulfill({ contentType: 'image/png', body: image }))
    await page.route('**/grade', route => {
      requests.push(route.request().postDataBuffer().toString())
      return route.fulfill({ contentType: 'application/json', body: JSON.stringify({ id: 'real-contract', capture_id: 'capture-contract', image_type: 'sashibocore', grade: 'GRADE_C', confidence: .91, scores: { GRADE_A: .03, GRADE_B: .04, GRADE_C: .91, INVALID: .02 } }) })
    })
    await page.goto(process.argv[2] || 'http://127.0.0.1:4185/')
    await page.locator('iframe[title="TunaEye"]').waitFor()
    const landing = page.frames().find(f => f.parentFrame())
    await expect(landing.locator('.hero')).toBeVisible()
    await landing.locator('[data-act="start"]').first().click()
    await landing.locator('#kiosk-wrap iframe').waitFor()
    const kiosk = page.frames().find(f => f.parentFrame() === landing)
    await kiosk.locator('#gs').click()
    await kiosk.locator('#in').fill('Exact UI QA')
    await kiosk.locator('#go').click()
    await expect(kiosk.getByRole('button', { name: 'Start live grading' })).toBeEnabled({ timeout: 15000 })
    await kiosk.getByRole('button', { name: 'Start live grading' }).click()
    await kiosk.locator('[data-k="8"]').click(); await kiosk.locator('[data-k="5"]').click()
    await kiosk.locator('#go').click()
    if (await kiosk.locator('#tps').isVisible()) await kiosk.locator('#tps').click()
    await expect(kiosk.locator('#sh')).toBeEnabled()
    await kiosk.locator('#sh').click()
    await expect(kiosk.locator('.med5-l')).toHaveText('C', { timeout: 20000 })
    if (!requests[0]?.includes('sashibocore')) throw Error('Pi image_type was not sent')
    const records = await page.evaluate(() => JSON.parse(localStorage.getItem('tunaeye-records') || '[]'))
    if (records[0]?.grade !== 'C' || records[0]?.result?.originalConfidence !== 91) throw Error('Model grade or confidence was not preserved')
    const evidenceBefore = await page.evaluate(async id => { const e = await (await import('/src/evidenceStorage.ts')).getCapturedEvidence(id); return Array.from(new Uint8Array(await e.blob.arrayBuffer())) }, records[0].capturedImageId)
    let rejections = 0
    await page.route('**/grade', route => { rejections++; return route.fulfill({ status: 422, contentType: 'application/json', body: JSON.stringify({ error: rejections === 1 ? 'sample_type_mismatch' : 'sample_type_unknown' }) }) })
    await kiosk.evaluate(() => go('core'))
    for (const message of ['Wrong sample type. Please upload a Sashibo Core image.', 'Sample type cannot be determined. Retake or upload another image.']) {
      await kiosk.locator('#fi').setInputFiles('public/assets/sashiboCoreFull.png')
      await expect(kiosk.getByRole('alert')).toContainText(message)
      await expect(kiosk.locator('#sh')).toBeVisible()
    }
    expect(rejections).toBe(2)
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem('tunaeye-records')))).toEqual(records)
    expect(await page.evaluate(async id => { const e = await (await import('/src/evidenceStorage.ts')).getCapturedEvidence(id); return Array.from(new Uint8Array(await e.blob.arrayBuffer())) }, records[0].capturedImageId)).toEqual(evidenceBefore)
    await kiosk.evaluate(() => go('final'))
    await kiosk.evaluate(() => {
      window.printCalls = []; window.failPrint = true
      document.addEventListener('load', event => { if (event.target.matches?.('iframe[data-thermal-receipt]')) event.target.contentWindow.print = () => { window.printCalls.push(performance.now()); if (window.failPrint) throw Error('Printer unavailable') } }, true)
      window.receiptEnteredAt = performance.now()
    })
    await kiosk.locator('#go').click()
    await expect(kiosk.locator('.rh1')).toBeVisible()
    await page.waitForTimeout(500)
    expect(await kiosk.evaluate(() => window.printCalls.length)).toBe(0)
    await expect.poll(() => kiosk.evaluate(() => window.printCalls.length)).toBe(1)
    expect(await kiosk.evaluate(() => window.printCalls[0] - window.receiptEnteredAt)).toBeGreaterThanOrEqual(950)
    await expect(kiosk.getByRole('alert')).toContainText('Printer not responding', { timeout: 10000 })
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem('tunaeye-records')).length)).toBe(1)
    fs.mkdirSync('test-results/receipt', { recursive: true }); await page.screenshot({ path: 'test-results/receipt/print-retry.png' })
    await kiosk.locator('#bk').click({ force: true }); await kiosk.locator('#go').click({ force: true })
    await expect(kiosk.locator('.rh1')).toBeVisible(); await kiosk.locator('#bk').click({ force: true })
    await expect(kiosk.locator('.med5-l')).toBeVisible()
    await page.waitForTimeout(1100)
    expect(await kiosk.evaluate(() => window.printCalls.length)).toBe(1)
    await kiosk.evaluate(() => { window.failPrint = false })
    await kiosk.locator('#go').click({ force: true }); await kiosk.locator('#orb').click({ force: true })
    await expect.poll(() => kiosk.evaluate(() => window.printCalls.length)).toBe(2)
    await page.waitForTimeout(1200)
    expect(await kiosk.evaluate(() => window.printCalls.length)).toBe(2)
    if (errors.length) throw Error(errors.join('\n'))
    console.log('PASS: Pi multipart capture; model Grade C at 91%; local record; receipt auto-prints after 1s; failure retains record; navigation cancels timer; manual print does not duplicate; no page errors or failed requests')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exit(1) })
