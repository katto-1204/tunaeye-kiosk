const { chromium, expect } = require('@playwright/test')
const fs = require('fs')
;(async () => {
  const b = await chromium.launch({ channel: 'chrome', headless: true, args: ['--disable-gpu', '--disable-software-rasterizer'] })
  try {
    fs.mkdirSync('test-results/version-history', { recursive: true })
    for (const viewport of [{ width: 1440, height: 1000 }, { width: 1024, height: 600 }, { width: 390, height: 844 }]) {
      const c = await b.newContext({ viewport }), p = await c.newPage(), errors = [], failed = []
      p.on('pageerror', e => errors.push(e.message))
      p.on('requestfailed', r => { if (r.url().startsWith('http://127.0.0.1:4185/')) failed.push(r.url()) })
      await p.goto('http://127.0.0.1:4185/', { waitUntil: 'domcontentloaded' })
      await p.locator('iframe[title="TunaEye"]').waitFor()
      const f = p.frames().find(x => x.parentFrame())
      await f.locator('.cl[data-act="log"]').click()
      const dialog = f.getByRole('dialog', { name: 'Version history.' })
      await expect(dialog).toBeVisible()
      await expect(dialog.locator('.history-entry')).toHaveCount(4)
      await expect(dialog.locator('.history-card li')).toHaveCount(13)
      await expect(dialog.locator('.history-current')).toHaveText('Latest release')
      const close = dialog.getByRole('button', { name: 'Close version history' })
      await expect(close).toBeFocused()
      await close.press('Shift+Tab')
      await expect(dialog.getByRole('button', { name: 'Back to TunaEye' })).toBeFocused()
      await dialog.getByRole('button', { name: 'Back to TunaEye' }).press('Tab')
      await expect(close).toBeFocused()
      const bounds = await dialog.locator('.history-panel').boundingBox()
      if (!bounds || bounds.x < 0 || bounds.y < 0 || bounds.x + bounds.width > viewport.width + 1 || bounds.y + bounds.height > viewport.height + 1) throw Error('Dialog exceeds viewport')
      await dialog.locator('.history-feed').evaluate(e => { e.scrollTop = e.scrollHeight })
      await expect(dialog.getByText('Grade A/B/C classification model training', { exact: true })).toBeVisible()
      await dialog.locator('.history-feed').evaluate(e => { e.scrollTop = 0 })
      await p.waitForTimeout(400)
      await p.screenshot({ path: `test-results/version-history/${viewport.width}.png` })
      await close.press('Escape')
      await expect(dialog).toHaveCount(0)
      await expect(f.locator('.cl[data-act="log"]')).toBeFocused()
      await f.locator('footer [data-act="log"]').click()
      await expect(dialog).toBeVisible()
      await dialog.getByRole('button', { name: 'Back to TunaEye' }).click()
      await expect(dialog).toHaveCount(0)
      await f.locator('.cl[data-act="log"]').click()
      await f.locator('#mo').click({ position: { x: 2, y: 2 } })
      await expect(dialog).toHaveCount(0)
      if (errors.length || failed.length) throw Error(JSON.stringify({ errors, failed }))
      console.log(`PASS version history ${viewport.width}x${viewport.height}: notes, scrolling, keyboard/focus, footer/trigger, backdrop; clean page/network`)
      await c.close()
    }
  } finally { await b.close() }
})().catch(e => { console.error(e); process.exit(1) })
